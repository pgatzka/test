-- Initial schema: one table holding every greeting the service has rendered.
CREATE TABLE greeting (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient     VARCHAR(100) NOT NULL,
    language_code VARCHAR(8)   NOT NULL,
    message       VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- Listing is filtered by language and ordered by recency, so index that pair.
CREATE INDEX idx_greeting_language_created_at ON greeting (language_code, created_at DESC);

COMMENT ON TABLE greeting IS 'Greetings rendered and stored by the service';
COMMENT ON COLUMN greeting.language_code IS 'ISO 639-1 code the greeting was rendered in';
